// Original Grade 2 informational-chart practice. Teacher evidence confirms only
// the "charts" topic; these examples are not teacher-issued test questions.
const make = (questionType,prompt,choices,answer,explanation,hint,dok,difficulty) =>
  Object.freeze({questionType,prompt,choices:Object.freeze(choices),answer,explanation,hint,dok,difficulty});

const questions = Object.freeze([
  make('direct',
    'In a chart of class pets, Cats = 6, Dogs = 4, and Fish = 2. Which pet has the highest count?',
    ['Cats','Dogs','Fish'], 'Cats',
    'Six cats is more than four dogs or two fish.',
    'Compare the three numbers and find the largest count.',1,2),
  make('direct',
    'A weather chart shows Monday = sunny, Tuesday = rainy, Wednesday = cloudy. What does its Tuesday row say?',
    ['rainy','sunny','cloudy'], 'rainy',
    'The Tuesday row of the chart is labeled rainy.',
    'Find the row for the second weekday, then read its weather.',1,2),
  make('direct',
    'A chart called Books Read lists Ava = 3, Ben = 5, and Eli = 2. Which student read five books?',
    ['Ava','Eli','Ben'], 'Ben',
    'Ben is paired with the number five in the Books Read chart.',
    'Find the row whose number matches the number in the question.',1,2),
  make('direct',
    'A chart called Favorite Fruit has columns Fruit and Votes. What does the Votes heading tell a reader?',
    ['how many votes each fruit received','how old each fruit is','when each fruit was picked'],
    'how many votes each fruit received',
    'The heading Votes identifies the number of votes shown for each fruit.',
    'Read the column title to know what the numbers below it represent.',1,2),
  make('transfer',
    'A bird-count chart lists blue birds = 7, green birds = 3, and red birds = 4. How many blue and green birds are there altogether?',
    ['9 birds','10 birds','11 birds'], '10 birds',
    'The chart shows seven blue birds and three green birds; 7 + 3 = 10.',
    'Locate the two named colors, then add their counts.',2,2),
  make('transfer',
    'The snack chart lists apples = 6, oranges = 2, and bananas = 5. How many more apples than oranges does it show?',
    ['3 more','5 more','4 more'], '4 more',
    'The apples row shows six and the oranges row shows two; 6 - 2 = 4.',
    'Find both fruit counts, then subtract the smaller from the larger.',2,2),
  make('transfer',
    'A library chart shows Monday = 3 visits, Tuesday = 5 visits, Wednesday = 1 visit. Which day matches five tally marks?',
    ['Wednesday','Tuesday','Monday'], 'Tuesday',
    'The row for Tuesday records five visits, equal to five tally marks.',
    'Use the count of tally marks to find the matching row.',2,2),
  make('transfer',
    'The plant-growth chart shows Sun = 2 inches, Rain = 4 inches, and Wind = 3 inches. Which plant grew one inch more than Sun?',
    ['Rain','Wind','Sun'], 'Wind',
    'Sun grew two inches; Wind grew three inches, which is one inch more.',
    'Start at two inches and find the plant one inch higher.',2,2),
  make('reasoning',
    'A bike-rider chart lists Monday = 5, Tuesday = 2, Wednesday = 6. Mia says Tuesday had the most riders. Which comparison corrects her?',
    ['Tuesday had the same count as Monday.','Wednesday had 6 riders, more than Tuesday had.','Tuesday had more riders than Wednesday.'],
    'Wednesday had 6 riders, more than Tuesday had.',
    'Wednesday has six riders while Tuesday has two, so Tuesday is not the greatest.',
    'Find the largest number in the chart and compare it with the Tuesday row.',3,3),
  make('reasoning',
    'A vote chart lists Apples = 4 votes and Grapes = 2 votes. Which question can you answer using only the chart?',
    ['Which student likes apples?','Why do students like fruit?','How many students voted for grapes?'],
    'How many students voted for grapes?',
    'The chart supplies counts, including two votes for grapes, but no names or reasons.',
    'Choose a question about information actually recorded in the rows.',3,3),
  make('reasoning',
    'A chart has column headings Day and Number of Books. Which heading should you use to find how many books were read?',
    ['Number of Books','Day','Neither heading'], 'Number of Books',
    'The Number of Books column contains book counts; Day tells when they were read.',
    'Match the quantity being asked about to its column heading.',3,3),
  make('reasoning',
    'A pet-choice chart lists Cats = 4, Dogs = 4, and Birds = 2. Which conclusion follows from the numbers?',
    ['Birds were chosen the most.','Cats and dogs received the same number of choices.','Dogs were chosen fewer times than birds.'],
    'Cats and dogs received the same number of choices.',
    'Cats and dogs both have four choices, so their counts are equal.',
    'Compare the rows and look for the two matching counts.',3,3),
]);

