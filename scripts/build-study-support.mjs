import {readFileSync,writeFileSync} from 'node:fs';
const source=name=>readFileSync(new URL('../pages/'+name,import.meta.url),'utf8');
// Keep maintainable source modules while shipping one small offline entry point.
const bundle='// Generated by scripts/build-study-support.mjs; edit the source modules.\n'+
  source('study-review.js')+'\n'+source('study-practice.js')+
  '\n(()=>{const style=document.createElement("style");style.dataset.abvmStudy="true";style.textContent='+JSON.stringify(source('study-review.css'))+';document.head.append(style)})();\n';
if(Buffer.byteLength(bundle)>14000)throw new Error('Study support bundle exceeds its 14 KB budget');
writeFileSync(new URL('../pages/study-support.js',import.meta.url),bundle);
